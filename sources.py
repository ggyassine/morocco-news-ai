# GOOGLE NEWS RSS
# ============================================================

def google_news(site, language="ar", country="MA"):
    return (
        "https://news.google.com/rss/search?"
        f"q=site%3A{site}"
        f"&hl={language}"
        f"&gl={country}"
        f"&ceid={country}%3A{language}"
    )


def google_query(query, language="ar", country="MA"):
    return (
        "https://news.google.com/rss/search?"
        f"q={query}"
        f"&hl={language}"
        f"&gl={country}"
        f"&ceid={country}%3A{language}"
    )


