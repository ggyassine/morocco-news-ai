# GOOGLE NEWS RSS HELPERS
# ============================================================

def google_news(
    site,
    language="ar",
    country="MA",
):
    """
    إنشاء رابط Google News RSS لموقع محدد.
    """

    return (
        "https://news.google.com/rss/search?"
        f"q={quote_plus(f'site:{site}')}"
        f"&hl={quote_plus(language)}"
        f"&gl={quote_plus(country)}"
        f"&ceid={quote_plus(f'{country}:{language}')}"
    )


def google_query(
    query,
    language="ar",
    country="MA",
):
    """
    إنشاء رابط Google News RSS لبحث عام.

    quote_plus مهم جدًا هنا لأن البحث قد يحتوي
    على كلمات عربية ومسافات.
    """

    encoded_query = quote_plus(query)

    return (
        "https://news.google.com/rss/search?"
        f"q={encoded_query}"
        f"&hl={quote_plus(language)}"
        f"&gl={quote_plus(country)}"
        f"&ceid={quote_plus(f'{country}:{language}')}"
    )


